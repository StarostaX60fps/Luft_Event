function apply() {
  var q = state.q.trim().toLowerCase();
  var shown = 0;
  var secs = 0;

  $$('.cat').forEach(function (s) {
    var inCat =
      state.cat === 'all' ||
      s.getAttribute('data-cat') === state.cat;

    var v = 0;

    $$('.card', s).forEach(function (c) {
      var ok = inCat &&
        (!q || c.getAttribute('data-search').indexOf(q) > -1);

      c.hidden = !ok;

      if (ok) v++;
    });

    s.hidden = v === 0;

    if (v) {
      shown += v;
      secs++;
    }

    var n = $('.n', s);

    if (n) {
      n.textContent = v +
        (v === 1 ? ' Produkt' : ' Produkte');
    }
  });

  $('#count').textContent =
    shown +
    (shown === 1 ? ' Produkt' : ' Produkte') +
    (state.cat === 'all'
      ? ' in ' + secs +
        (secs === 1 ? ' Kategorie' : ' Kategorien')
      : '');

  $('#empty').hidden = shown > 0;

  $$('.chip').forEach(function (b) {
    var on = b.getAttribute('data-cat') === state.cat;

    b.setAttribute('aria-pressed', String(on));

    if (on) {
      var l = b.firstChild.textContent;
      var n = $('.cn', b).textContent;

      $('#catVal').textContent = l + ' (' + n + ')';
    }
  });
}

