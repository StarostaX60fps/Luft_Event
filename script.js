function count() {
  return cart.reduce(function (a, i) {
    return a + i.qty;
  }, 0);
}

function renderCart() {
  var n = count();
  var cc = $('#cartCount');

  cc.textContent = n;

  $('#cartOpen').setAttribute(
    'aria-label',
    'Warenkorb öffnen, ' + n + ' Artikel'
  );

  cc.classList.remove('bump');
  void cc.offsetWidth;
  cc.classList.add('bump');

  var box = $('#cartBody');
  var total = 0;

  if (!cart.length) {
    box.innerHTML =
      '<div class="cart-empty">' +
      '<p><strong>Ihr Warenkorb ist leer.</strong></p>' +
      '<p>Wählen Sie im Katalog ein Produkt und klicken Sie auf „Termin buchen“.</p>' +
      '</div>';

    $('#cartFoot').hidden = true;
    $('#agree').checked = false;
    $('#orderBtn').disabled = true;

    return;
  }

  $('#cartFoot').hidden = false;

  box.innerHTML =
    '<ul class="clist">' +
    cart.map(function (i, ix) {
      var p = P.filter(function (x) {
        return x.id === i.id;
      })[0];

      if (!p) return '';

      total += p.price * i.qty;

      var ic = $(
        '.card[data-id="' + p.id + '"] .ic'
      ).outerHTML;

      return (
        '<li class="ci">' +
          '<div class="tile g' + i.col + ' sm" aria-hidden="true">' +
            ic +
          '</div>' +

          '<div class="cit">' +
            '<p class="n">' + p.name + '</p>' +
            '<p class="m">Farbe: ' + COL[i.col] + '</p>' +
            '<p class="m">Termin: ' +
              fS.format(fromKey(i.date)) +
            '</p>' +

            '<div class="qty sm" role="group" aria-label="Menge">' +
              '<button type="button" data-ix="' + ix +
                '" data-d="-1" aria-label="Menge verringern">−</button>' +
              '<output>' + i.qty + '</output>' +
              '<button type="button" data-ix="' + ix +
                '" data-d="1" aria-label="Menge erhöhen">+</button>' +
            '</div>' +
          '</div>' +

          '<div class="cip">' +
            '<span class="price">' +
              fmt(p.price * i.qty) +
            '</span>' +
            '<button class="lnk" type="button" data-rm="' +
              ix + '">Entfernen</button>' +
          '</div>' +
        '</li>'
      );
    }).join('') +
    '</ul>';

  $('#ctotal').textContent = fmt(total);

  upd();
}

function upd() {
  $('#orderBtn').disabled = !(
    cart.length && $('#agree').checked
  );
}

