function key(d) {
  return d.getFullYear() + '-' +
    String(d.getMonth() + 1).padStart(2, '0') + '-' +
    String(d.getDate()).padStart(2, '0');
}

function fromKey(k) {
  var a = k.split('-');
  return new Date(+a[0], +a[1] - 1, +a[2]);
}

function busy(d) {
  return (d.getDate() + d.getMonth() * 3) % 6 === 0;
}

