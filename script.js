/* ---------- Cookie-настройки ---------- */

var ck = $('#cookie');
var KEY = 'le-consent';

function saved() {
  try {
    return localStorage.getItem(KEY);
  } catch (e) {
    return null;
  }
}

function save(v) {
  try {
    localStorage.setItem(KEY, v);
  } catch (e) {}
}

function showCk(open) {
  ck.hidden = false;

  document.documentElement.style.setProperty(
    '--cb',
    ck.offsetHeight + 'px'
  );

  if (open) {
    $('#ckSet').hidden = false;
  }
}

function hideCk() {
  ck.hidden = true;

  document.documentElement.style.setProperty(
    '--cb',
    '0px'
  );
}

if (!saved()) {
  showCk();
}

ck.addEventListener('click', function (e) {
  var b = e.target.closest('[data-ck]');

  if (!b) return;

  var a = b.getAttribute('data-ck');

  if (a === 'set') {
    var s = $('#ckSet');

    s.hidden = !s.hidden;

    b.setAttribute(
      'aria-expanded',
      String(!s.hidden)
    );

    document.documentElement.style.setProperty(
      '--cb',
      ck.offsetHeight + 'px'
    );

    return;
  }

  if (a === 'all') {
    $('#ckStat').checked = true;
    $('#ckExt').checked = true;
  }

  if (a === 'nec') {
    $('#ckStat').checked = false;
    $('#ckExt').checked = false;
  }

  save(JSON.stringify({
    stat: $('#ckStat').checked,
    ext: $('#ckExt').checked
  }));

  hideCk();

  toast('Ihre Auswahl wurde gespeichert');
});

$$('[data-cookie]').forEach(function (b) {
  b.addEventListener('click', function () {
    showCk(true);

    $('[data-ck="set"]').setAttribute(
      'aria-expanded',
      'true'
    );

    ck.querySelector('button').focus();
  });
});

window.addEventListener('resize', function () {
  if (!ck.hidden) {
    document.documentElement.style.setProperty(
      '--cb',
      ck.offsetHeight + 'px'
    );
  }
});

/* ---------- Анимации при прокрутке ---------- */

var motionTargets = $$('.card,.cat-h,.cat-head,.steps,.contact,.foot-grid,.hero-art');

if (
  !reduce &&
  'IntersectionObserver' in window
) {
  var revealObserver = new IntersectionObserver(
    function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible');

          revealObserver.unobserve(entry.target);
        }
      });
    },
    {
      threshold: 0.08,
      rootMargin: '0px 0px -28px 0px'
    }
  );

  motionTargets.forEach(function (el) {
    el.classList.add('reveal-ready');

    revealObserver.observe(el);
  });
} else {
  motionTargets.forEach(function (el) {
    el.classList.add('is-visible');
  });
}

